"""Pydantic schemas for ItemPilot listing input and output data."""

from typing import Dict, List, Optional
from pydantic import BaseModel, Field, field_validator


class SellerInput(BaseModel):
    """Optional seller-provided item specifics and context."""
    category: Optional[str] = Field(default=None, description="Product category or name")
    brand: Optional[str] = Field(default=None, description="Brand name if known")
    model_sku: Optional[str] = Field(default=None, description="Model number or SKU")
    condition: Optional[str] = Field(default=None, description="Item condition")
    color: Optional[str] = Field(default=None, description="Primary color(s)")
    material: Optional[str] = Field(default=None, description="Material or fabric")
    size_dimensions: Optional[str] = Field(default=None, description="Size or dimensions")
    features: Optional[str] = Field(default=None, description="Known features or extras")
    writing_style: Optional[str] = Field(default="Clear and informative", description="Listing copy tone and style")


class ListingOutput(BaseModel):
    """Structured eBay listing generated by the local AI model."""
    title: str = Field(
        ...,
        min_length=1,
        max_length=80,
        description="eBay listing title, strictly 80 characters or fewer"
    )
    promotional_tagline: Optional[str] = Field(
        default=None,
        description="Optional promotional tagline or eBay subtitle (under 55 characters)"
    )
    description: str = Field(
        ...,
        min_length=1,
        description="Structured, persuasive eBay description"
    )
    features: List[str] = Field(
        default_factory=list,
        description="Key product bullet points visible or verified"
    )
    keywords: List[str] = Field(
        default_factory=list,
        description="High-value search keywords and tags"
    )
    item_specifics: Dict[str, Optional[str]] = Field(
        default_factory=dict,
        description="Item attributes (brand, model, color, material, etc.)"
    )
    missing_info: List[str] = Field(
        default_factory=list,
        description="Critical missing details required or recommended before listing"
    )

    @field_validator("title")
    @classmethod
    def validate_title_length(cls, v: str) -> str:
        clean = v.strip()
        if not clean:
            raise ValueError("Listing title cannot be empty.")
        if len(clean) > 80:
            raise ValueError(f"Title exceeds 80 characters (got {len(clean)} characters).")
        return clean
